#!/usr/bin/env python3
"""Generates crates/oa-math/src/consts.rs: the constants and small tables behind oa-math.

Dev tool only (mpmath 1.3.0); nothing here is a build dependency.
Usage: python3 tools/oa-math-ref/gen_consts.py > crates/oa-math/src/consts.rs
"""
from mpmath import mp, mpf, pi, log, exp, sin, cos, atan, floor, frexp, ldexp, factorial

mp.prec = 1800


def dd(v):
    hi = float(v)
    lo = float(v - mpf(hi))
    return hi, lo


def trunc_bits(v, nbits):
    """v truncated (toward zero) to nbits significant bits."""
    m, e = frexp(v)
    return ldexp(floor(m * mpf(2) ** nbits), e - nbits)


def f(v):
    return repr(float(v))


out = []
w = out.append
w("// Generated by tools/oa-math-ref/gen_consts.py (mpmath 1.3.0). Do not edit by hand.")
w("//! Constants and small tables for the elementary functions. Every value is a double or a")
w("//! double-double (hi, lo) rounded from a 1800-bit mpmath evaluation.")
w("")
w("// The tables hold the mathematical constants on purpose, rounded here, not std's copies.")
w("#![allow(clippy::approx_constant)]")
w("")
w("use crate::dd::{dd, Dd};")
w("")

# pi/2 for Cody-Waite reduction: three 33-bit pieces (n * piece is exact for n < 2^19) and a rest.
pio2 = pi / 2
p1 = trunc_bits(pio2, 33)
r1 = pio2 - p1
p2 = trunc_bits(r1, 33)
r2 = r1 - p2
p3 = trunc_bits(r2, 33)
r3 = r2 - p3
p4 = float(r3)
w("/// pi/2 in pieces for Cody-Waite reduction: three 33-bit pieces and the rounded rest.")
w(f"pub(crate) const PIO2_1: f64 = {f(p1)};")
w(f"pub(crate) const PIO2_2: f64 = {f(p2)};")
w(f"pub(crate) const PIO2_3: f64 = {f(p3)};")
w(f"pub(crate) const PIO2_4: f64 = {p4!r};")
h, l = dd(pio2)
w(f"pub(crate) const PIO2_DD: Dd = dd({h!r}, {l!r});")
w(f"pub(crate) const PIO2_HI: f64 = {h!r};")
h, l = dd(pi)
w(f"pub(crate) const PI_DD: Dd = dd({h!r}, {l!r});")
w(f"pub(crate) const PI_HI: f64 = {h!r};")
w(f"pub(crate) const PIO4_HI: f64 = {float(pi/4)!r};")
w(f"pub(crate) const THREE_PIO4_HI: f64 = {float(3*pi/4)!r};")
w(f"pub(crate) const TWO_OVER_PI: f64 = {float(2/pi)!r};")
w("")

# 2/pi bits for Payne-Hanek: word 0 holds the first 64 fractional bits, most significant first.
NW = 22
bits = int(floor(2 / pi * mpf(2) ** (64 * NW)))
words = [(bits >> (64 * (NW - 1 - i))) & (2**64 - 1) for i in range(NW)]
w("/// Fractional bits of 2/pi, 64 per word, first word most significant (Payne-Hanek).")
w(f"pub(crate) const TWO_OVER_PI_BITS: [u64; {NW}] = [")
for x in words:
    w(f"    0x{x:016x},")
w("];")
w("")

ln2 = log(mpf(2))
w("/// ln 2 / 64 in pieces (35 + 35 bits and the rest) for exp reduction; the multiplier is below 2^17.")
a1 = trunc_bits(ln2 / 64, 35)
a2 = trunc_bits(ln2 / 64 - a1, 35)
a3 = float(ln2 / 64 - a1 - a2)
w(f"pub(crate) const LN2_64_1: f64 = {f(a1)};")
w(f"pub(crate) const LN2_64_2: f64 = {f(a2)};")
w(f"pub(crate) const LN2_64_3: f64 = {a3!r};")
w(f"pub(crate) const INV_LN2_64: f64 = {float(64/ln2)!r};")
h, l = dd(ln2)
w(f"pub(crate) const LN2_DD: Dd = dd({h!r}, {l!r});")
w("")

w("/// 2^(j/64) for j = 0..63 as double-doubles.")
w("pub(crate) const EXP_TAB: [Dd; 64] = [")
for j in range(64):
    h, l = dd(mpf(2) ** (mpf(j) / 64))
    w(f"    dd({h!r}, {l!r}),")
w("];")
w("")

w("/// Taylor coefficients 1/6, 1/24, ..., 1/8! (exp tail, from the r^3 term).")
w("pub(crate) const EXP_C: [f64; 6] = [")
for k in range(3, 9):
    w(f"    {float(1/factorial(k))!r},")
w("];")
w("")

# ln: bins j = floor(m * 64) for m in [0.75, 1.5); r is 1/centre rounded to 10 fractional bits,
# except the two bins around 1 where r = 1 so that m - 1 is exact.
w("/// Log reduction table for m in [0.75, 1.5), bin j = floor(64 m) = 48..95: the multiplier r")
w("/// (1 in the two bins around 1) and -ln r as a double-double.")
w("pub(crate) const LN_R: [f64; 48] = [")
rs = []
for j in range(48, 96):
    if j in (63, 64):
        r = mpf(1)
    else:
        c = (mpf(j) + mpf(1) / 2) / 64
        r = floor(mpf(1) / c * 1024 + mpf(1) / 2) / 1024
    rs.append(r)
    w(f"    {f(r)},")
w("];")
w("pub(crate) const LN_NEG_LN_R: [Dd; 48] = [")
for r in rs:
    h, l = dd(-log(r))
    w(f"    dd({h!r}, {l!r}),")
w("];")
w("")
w("/// log1p tail coefficients: -1/4, 1/5, ..., (-1)^(k+1)/(k+4) for k = 0..10 (u^4 term onward).")
w("pub(crate) const LN_C: [f64; 11] = [")
for k in range(11):
    w(f"    {float(mpf(-1) ** (k + 1) / (k + 4))!r},")
w("];")
h, l = dd(mpf(1) / 3)
w(f"pub(crate) const INV3_DD: Dd = dd({h!r}, {l!r});")
h, l = dd(mpf(1) / 6)
w(f"pub(crate) const INV6_DD: Dd = dd({h!r}, {l!r});")
w("")

w("/// sin(j/16) and cos(j/16) for j = 0..14 as double-doubles.")
w("pub(crate) const SIN_TAB: [Dd; 15] = [")
for j in range(15):
    h, l = dd(sin(mpf(j) / 16))
    w(f"    dd({h!r}, {l!r}),")
w("];")
w("pub(crate) const COS_TAB: [Dd; 15] = [")
for j in range(15):
    h, l = dd(cos(mpf(j) / 16))
    w(f"    dd({h!r}, {l!r}),")
w("];")
w("/// sin b tail coefficients: 1/5!, -1/7!, 1/9!, -1/11! (b^5 term onward).")
w("pub(crate) const SIN_C: [f64; 4] = [")
for k, n in enumerate((5, 7, 9, 11)):
    w(f"    {float(mpf(-1) ** k / factorial(n))!r},")
w("];")
w("/// cos b tail coefficients: 1/4!, -1/6!, 1/8!, -1/10!, 1/12! (b^4 term onward).")
w("pub(crate) const COS_C: [f64; 5] = [")
for k, n in enumerate((4, 6, 8, 10, 12)):
    w(f"    {float(mpf(-1) ** k / factorial(n))!r},")
w("];")
w("")
w("/// atan(j/16) for j = 0..16 as double-doubles.")
w("pub(crate) const ATAN_TAB: [Dd; 17] = [")
for j in range(17):
    h, l = dd(atan(mpf(j) / 16))
    w(f"    dd({h!r}, {l!r}),")
w("];")
w("/// atan u tail coefficients: 1/5, -1/7, 1/9, -1/11, 1/13 (u^5 term onward).")
w("pub(crate) const ATAN_C: [f64; 5] = [")
for k, n in enumerate((5, 7, 9, 11, 13)):
    w(f"    {float(mpf(-1) ** k / n)!r},")
w("];")
print("\n".join(out))
