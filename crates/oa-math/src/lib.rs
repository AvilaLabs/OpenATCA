#![forbid(unsafe_code)]
#![cfg_attr(not(test), no_std)]
//! oa-math: elementary functions that give the same bits on every IEEE-754 machine.
//!
//! Core (pure) code. `no_std` outside tests, no allocation, no panic path. Its one dependency is
//! `oa-ieee`, the five exactly specified operations `core` lacks (see the README).
//!
//! # Why this crate exists
//!
//! The tracker, the replay and the record-and-compare tooling must reproduce a run bit for bit
//! (RULESET B6). The maths library behind `f64::sin`, `f64::exp`, `f64::powf` and the rest is
//! the platform's own: its results differ between operating systems, libm versions and CPU
//! feature levels, in the last bit or more. A replay on another machine would then diverge.
//! This crate computes those functions itself.
//!
//! # The determinism rule
//!
//! Only operations that IEEE-754 requires to be correctly rounded are used: `+ - * /`,
//! `oa_ieee::sqrt`, the float remainder `%` (`fmod`, which IEEE-754 makes exact, used only by
//! [`rem_euclid`]), integer arithmetic and bit casts (`to_bits`, `from_bits`). Nothing calls the
//! platform maths library, not even on a fallback path (a test greps the sources for the
//! forbidden calls), and nothing relies on fused multiply-add (a separate multiply and add are
//! never contracted by the compiler). Rounding is round-to-nearest-even, the Rust default.
//! Every NaN returned is one fixed bit pattern. The same inputs therefore give the same output
//! bits on any IEEE-754 machine; the pinned value of `tests/fingerprint.rs` (one hash over a
//! million results) has been checked on x86-64 and wasm32 only, aarch64 has not been run.
//!
//! # How the accuracy is reached
//!
//! Each function computes in double-double arithmetic (about 106 bits), so the only large error
//! is the final rounding to a double. Results are faithfully rounded (error below 1 ulp), and
//! in practice correctly rounded except when the true value lies within about 2^-70 relative of
//! a rounding midpoint. The constants and tables are generated by
//! `tools/oa-math-ref/gen_consts.py` with mpmath and live in `consts.rs`. The reference data in
//! `tests/data` is generated by `tools/oa-math-ref/gen_ref.py`.
//!
//! # The fast path
//!
//! Each function first tries a fast path in plain double arithmetic (short series, a few
//! error-free transformations where the error matters), with a derived absolute error bound `err`
//! (the derivations are in the comments of each module). If `h + l` is the fast result, the
//! rounding test of Ziv's method (`util::round_test`) checks that `h + (l + err)` and
//! `h + (l - err)` round to the same double; when they do, the true value cannot lie on the
//! other side of a rounding boundary and that double is returned. Otherwise (about one call in
//! 20 to 100 in the typical ranges, more near the hard cases, and every argument the fast path
//! does not handle: huge arguments, subnormals, special values) the double-double path
//! described below runs. As that path returns the correctly rounded double wherever the fast path answers (the
//! fast path's margin covers the slow path's own error, which for `pow` grows with |y ln x|), the
//! results are the same bits as before the fast path existed; `tests/fingerprint.rs` is
//! unchanged and `src/fast_tests.rs` compares the two paths on a million inputs per function.
//!
//! # Measured accuracy
//!
//! Maximum error against a correctly rounded mpmath reference, in ulps of the true value
//! (`cargo test -p oa-math --test reference -- --nocapture` prints it). The 3,200 committed
//! cases per function and a one-off run of 60,000 per function (another seed, same
//! distribution) agree: every maximum is 0.5 ulp to within 1e-5, the rounding of the final
//! result. Against the correctly rounded value, none of the 3,200 + 60,000 cases of any function
//! except `pow` differs; `pow` differs in 19 of the 63,200, each a result within 2^-70
//! (relative) of a rounding midpoint, one ulp from the correctly rounded value but still under
//! 0.5000005 ulp from the true one.
//!
//! | function | max error (ulp) | domain tested |
//! |---|---|---|
//! | [`sin`] | 0.499996 | all finite, hard reduction cases, subnormals, up to `f64::MAX` |
//! | [`cos`] | 0.499992 | same |
//! | [`tan`] | 0.499998 | same |
//! | [`atan`] | 0.499996 | all finite |
//! | [`asin`], [`acos`] | 0.499997, 0.499994 | [-1, 1], near 1 and near 0 |
//! | [`atan2`] | 0.5000 | all finite pairs, ratios beyond 2^60 |
//! | [`exp`] | 0.5000 | all, including subnormal results |
//! | [`ln`] | 0.5000 | all positive, subnormals, near 1 |
//! | [`pow`] | 0.5000 | `y ln x` up to the overflow limit, subnormal results |
//! | [`hypot`] | 0.5000 | all finite pairs |
//! | [`cbrt`] | 0.499995 | all finite, both signs, subnormals |
//!
//! [`powi`] is within one ulp, not faithfully rounded: its double-double chain carries a relative
//! error of about `|n|` 2^-104 before the one final rounding (see its docs).
//!
//! | function | method |
//! |---|---|
//! | [`sin`], [`cos`], [`sin_cos`], [`tan`] | Cody-Waite below 2^19, Payne-Hanek above; table and series |
//! | [`atan`], [`atan2`], [`asin`], [`acos`] | ratio in double-double, table at j/16, series |
//! | [`exp`] | ln 2 / 64 reduction, table 2^(j/64), Taylor tail |
//! | [`ln`] | table of reciprocals, log1p series |
//! | [`pow`] | double-double ln and exp, valid to the overflow limit |
//! | [`powi`] | double-double repeated squaring of the mantissa, one final scaled rounding |
//! | [`hypot`], [`cbrt`] | scaled double-double square root; Newton with a double-double step |
//!
//! Speed: roughly 1.2 to 4 times the platform library per call with the fast path, 2 to 12 times
//! without it (an `examples/speed.rs` run prints the table); the price of the determinism and
//! the extra accuracy.

